# 附件 / 文件引用标记（程序生成，不是用户说的话）—— 见 strip_attachment_refs。
_ATTACH_REF_RE = re.compile(
    r"\[(?:\u56fe\u7247\u5df2\u7c98\u8d34)\s*\d*\]"
    r"|\[(?:\u6587\u4ef6\u4e0d\u5b58\u5728|\u975e\u56fe\u7247\u6587\u4ef6|\u6587\u4ef6|file)"
    r"\s*:\s*[^\]\n]*\]")


def strip_attachment_refs(text):
    """剥掉附件 / 文件引用标记（v4.173.0）—— **本函数是该处理的唯一来源**。

    标记里装的是**文件名或路径**（如「导演台模块改进建议_v4.164.0.md」），
    属程序生成的元信息，**不是用户说的话**。而所有判据都拿原始消息做关键词匹配，
    于是文件名会把判据点着。实测两起事故（都在 2026-09-27 验收时暴露）：

      · 附件名「导演台模块改进建议.md」与「…BUG修改方案.md」**分别**贡献了
        「导演台」和「修改」，凑成一对 → 整条消息被判成导演台指令 → **被吞掉不处理**；
      · 只附一个「不要跟陌生人说话.md」（29 字，在长度闸内）→ 判据读到「不要」
        → 判成「用户喊停」→ 本轮强制 `tool_choice="none"` → **整轮禁止工具**。

    故在归一化入口 `_norm()` 里统一剥掉，各判据不必自己记得处理。
    `ui._strip_attachment_refs` 是它的转发别名（导演台判据也用同一份）。
    """
    if not text:
        return ""
    return _ATTACH_REF_RE.sub(" ", text)


def _norm(text):
    """判据的**统一归一化入口**：先剥附件引用，再修首尾空白。

    所有对外判据（`explain` / `_reasons` / `is_action_instruction`）都经此处取文本，
    所以「附件名点着判据」这类问题在入口一次性解决 —— 不依赖每个判据自己记得处理。
    """
    return strip_attachment_refs(text).strip()


def _neg_hits(text):
    """找出文本里所有否定词，返回 [(位置, 词), ...]。

    **识别口径的唯一来源**：`is_negation` 与 `_neg_is_constraint` 都从这里取。
    分两处各写一遍词表逻辑，迟早会漂移（改一处忘另一处 = 判据静默不一致）。
    """
    out = []
    for k in _NEG_PHRASES:
        i = text.find(k)
        if i >= 0:
            out.append((i, k))
    for m in re.finditer("别", text):
        i = m.start()
        if i > 0 and text[i - 1] in _NEG_COMPOUND_BEFORE:
            continue          # 复合词的一部分，非否定词
        if text[i:i + 2] == "别扭":
            continue
        tail0 = text[i + 1:i + 2]
        if tail0 in _NEG_TAIL_VERB or tail0 in _NEG_TAIL_PARTICLE:
            out.append((i, "别"))
    return out


def _neg_is_constraint(text):
    """否定词是不是在「约束某个做法」而非「叫停任务」。

    位置判据：消息里先出现正向任务祈使（"抓取…""整理…""写入…"），
    否定词出现在它**之后** ⇒ 前面已经在下达任务了，后面这句否定只能是约束。

        「抓取今天的新闻，不要盲目上浏览器」   → 任务@0，不要@8 → 约束
        「整理成简报，不要编造日期或来源」     → 任务@0，不要@5 → 约束
        「别生成视频了」                       → 否定@0，不晚于任务动词 → 不是约束
        「刚才那个不要了，重新来一个」           → 否定@4 < "重新"… → 不是约束

    为什么需要它：中文里「不要」在指令中的**常见用法就是加约束**
    （不要超字数、不要编造、不要用浏览器）。旧判据一见「不要」就整轮关工具，
    会把「抓取新闻，不要盲目上浏览器」这种再普通不过的指令直接判死。
    """
    hits = _neg_hits(text)
    if not hits:
        return False
    first_neg = min(p for p, _ in hits)
    m = _TASK_VERB_RE.search(text)
    return bool(m) and first_neg > m.end()


def is_negation(text):
    """是否「取消 / 拒绝 / 喊停」—— 一票否决，绝不为它调工具。

    v4.159.4 定式：裸「别」字不用前向白名单枚举（辨别/识别/类别/个别/送别/
    别扭 永远补不完），改「前向复合词闭集豁免 + 后向紧贴一字判据」。

    v4.168.3 加两道闸（实测事故根因）：
      自动化任务「每日 AI 新闻抓取」全文 759 字，里面写着「不要盲目上浏览器」
      「不要据此判定」—— 这是**约束做法**，不是叫停任务。旧判据只要出现
      「不要」就一票否决 → 整条消息判为非指令 → 层 3 强制 `tool_choice="none"`
      → **任务被禁止调工具**（抓新闻必须调工具），任务直接瘫痪。

      闸一（长度）：喊停是短句（「别做了」4 字、「取消」2 字，实测自然喊停句
        最长约 30 字），任务说明书 / 需求描述动辄上百字 → 超长不做否定判定。
      闸二（位置）：见 `_neg_is_constraint` —— 否定词在任务祈使之后 = 在加约束。
      实测：「抓取今天的新闻，不要盲目上浏览器，优先 RSS」（23 字）闸一拦不住、
        闸二拦得住 —— 两道闸互补，缺一不可。

      取舍理由：漏拦一句较长的喊停（模型仍能从语义看出该停）远轻于
      错杀一条任务（100% 跑不起来）。
    """
    if not text:
        return False
    if not _neg_hits(text):
        return False
    if len(_norm(text)) > _NEG_MAX_LEN:
        return False
    if _neg_is_constraint(text):
        return False
    return True


def has_imperative(text):
    """是否含明确祈使 / 续接指令 —— 评价与咨询判据的一票反否决。"""
    if not text:
        return False
    t = text.lower()
    return any(k in t for k in _IMPERATIVE_KW)


def is_praise(text):
    """是否「纯评价 / 夸赞」而非动作指令。

    「这个视频生成得真不错」「刚才图片做得太惊艳了」「Agnes 的视频效果真强」
    这些句子里同时出现了媒体对象词（视频/图片）与动作词（生成/制作），
    旧判据的「对象词 × 动作词同现」必然误判 —— 这里先认评价结构。
    """
    if not text:
        return False
    if has_imperative(text):
        return False           # 「做得不错，继续」是真指令
    if _PRAISE_COMPLEMENT_RE.search(text):
        return True
    t = text.lower()
    return any(k in t for k in _PRAISE_KW)


def is_learning_question(text):
    """是否「学习 / 科普 / 了解」类纯咨询问句。"""
    if not text:
        return False
    if has_imperative(text):
        return False
    t = text.lower()
    return any(k in t for k in _LEARNING_KW)


def is_howto_question(text):
    """是否在问「这一步是怎么做到的」—— 要答案，不要产物。"""
    if not text:
        return False
    if has_imperative(text):
        return False
    t = text.lower()
    return any(k in t for k in _HOWTO_KW)


def is_ref_context(text):
    """是否在「引用 / 质疑 / 讨论」某个生成动作，而非下达它。

    两条腿：
      · 显式引用标记（「你刚才说的生成个视频，是BUG」）
      · 位置判据：元话语动词出现在生成短语之前且同分句
        （「分析下生成视频这件事」→ 生成短语是被分析的对象）
    """
    if not text:
        return False
    if any(k in text for k in _STRONG_REF_KW):
        return True
    m = _GEN_PHRASE_RE.search(text)
    if not m:
        return False
    prefix = text[:m.start()]
    if any(sep in prefix for sep in _CLAUSE_SEP):
        return False           # 「生成个视频，顺便分析下」→ 生成是独立指令
    if any(mv in prefix for mv in _META_VERBS):
        return True
    # v4.186.0（P1-2 修）：后置质疑句 ——「生成视频这件事你怎么看」。
    # 元话语动词在生成短语**之后**且同一分句内（到匹配点为止无分隔符/连接词）。
    # 「生成视频，你怎么看」带分隔符的仍放行（歧义：可能是"做完了再问意见"）。
    suffix = text[m.end():]
    pm = _POST_REF_RE.search(suffix)
    if pm and not any(sep in suffix[:pm.start()] for sep in _CLAUSE_SEP):
        return True
    return False


def is_discuss_tool_use(text):
    """是否在「讨论 / 追问 / 评估某个工具动作」，而不是下达它（v4.169.0 新增）。

    为什么需要它
    ------------
    原有判据（praise / ref / learning / howto）几乎都围绕**媒体生成**打转：
    动补评价「这个视频生成得真不错」、生成短语引用「分析下生成视频这件事」。
    但用户大量说的是**别的工具语境**，实测以下四句全部漏放：

        「为什么会自动搜索？」
        「为什么打开文件会触发工具？」
        「下面这句提示是否危险：运行 Python 删除文件」
        「为什么会自动创建定时任务？」

    后三句里含「打开文件 / 运行 Python / 定时」等词，会命中 UI 的关键词路由
    **自动进入 Agent**，而判据不拦 → 模型被允许真去执行。它们本质上是在
    **问原因 / 评估一段草稿**，不是在下命令。

    判据（要求同时具备两件事，缺一不可）
    ------------------------------------
      ① **讨论信号**（`_DISCUSS_KW`）：为什么 / 怎么会 / 是否危险 / 会不会 /
         下面这句 / 会触发 … —— 说明用户在问、在评，不在派活；
      ② **工具动作语义**（`_TOOL_ACTION_RE` 或工具领域词）—— 说明被讨论的
         确实是一个工具动作（否则"为什么会下雨"不该被拦）。

    为什么不用「只要含疑问词就拦」：会把「为什么会自动搜索？顺便帮我关掉它」
    这种**带真指令**的句子也拦掉。故先让 `has_imperative` 一票反否决
    （与 praise / learning 同一套纪律），再判双条件。
    """
    if not text:
        return False
    # v4.169.0：引述切分 —— 冒号/引号后面往往是**被引用、被评估的文本**，
    # 不是用户的指令。反否决只看**主句**里的祈使。
    #   实测：「这段提示安全吗：帮我运行命令」—— "帮我"属于引文，
    #   若拿它做 imperative 反否决，整句反而漏拦（那正是要拦的句子）。
    #   而「为什么会自动搜索？顺便帮我关掉它」的主句里真有"帮我" → 该放行。
    _head = re.split(r"[：:；;]", text, maxsplit=1)[0]
    if has_imperative(_head):
        return False           # 主句里有明确祈使 → 真指令，不拦
    if not any(k in text for k in _DISCUSS_KW):
        return False
    if _TOOL_ACTION_RE.search(text):
        return True
    return any(k in text for k in _TOOL_DOMAIN_KW)


def is_pure_statement(text):
    """是否「纯陈述 / 感慨」—— 有陈述色彩且无执行意图词。"""
    if not text:
        return False
    t = text.lower()
    if not any(h.lower() in t for h in _STATEMENT_HINTS):
        return False
    if has_imperative(text):
        return False
    return not any(h in t for h in _ACTION_HINT_KW)


# 与 ui._ACTION_HINTS 同源的「执行意图词」最小集（用于纯陈述判定）。
_ACTION_HINT_KW = (
    "搜索", "搜", "查", "写", "生成", "做", "执行", "分析", "整理", "导出",
    "下载", "安装", "运行", "创建", "打开", "发", "截图", "提醒", "翻译", "总结",
    "爬", "抓", "监控", "帮我", "请", "处理", "改", "修", "看下", "看看",
)


