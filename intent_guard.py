# 对外主入口
# ==========================================================================

def explain(text):
    """返回命中原因明细（诊断 / 测试用）。"""
    t = _norm(text)
    return {
        "text": t,
        "negation": is_negation(t),
        "praise": is_praise(t),
        "learning": is_learning_question(t),
        "howto": is_howto_question(t),
        "ref": is_ref_context(t),
        "statement": is_pure_statement(t),
        "imperative": has_imperative(t),
    }


def _reasons(text):
    t = _norm(text)
    if not t:
        return []
    out = []
    if is_negation(t):
        out.append("negation")
    if is_praise(t):
        out.append("praise")
    if is_learning_question(t):
        out.append("learning")
    if is_howto_question(t):
        out.append("howto")
    if is_ref_context(t):
        out.append("ref")
    return out


def is_non_action_message(text):
    """这条消息是否**明显不是**动作指令（层 1 / 层 2 用）。

    True → UI 不自动进 Agent；Agent 不置 `_needs_action`。
    范围＝否定 / 引用 / 评价 / 咨询 / 方法疑问。

    刻意**不含**「状态追问」：Agent 模式下问「任务进度如何」是合法操作
    （要调 task_status），把它当非指令会把真功能关掉。
    """
    return bool(_reasons(text))


def blocks_tool_call(text):
    """模型调用层的最终保险：这条消息是否该强制 `tool_choice="none"`。

    能同时挡住三件事：
      · 非推理模型被 `required` 强制调用；
      · 推理模型看见全量 tools 后自行调用；
      · 系统提示里「命中关键词必须调用」把模型带偏。
    """
    return bool(_reasons(text))


def why_blocked(text):
    """返回命中的原因标签列表（空列表＝不拦截）。"""
    return _reasons(text)


def is_action_instruction(text):
    """反向判据：是否**明确**要动作。供测试与文档对照用。

    注意：这不是 `is_non_action_message` 的简单取反 —— 大多数句子既不是
    明确非指令、也不是明确指令（模棱两可），此时应交给模型自由决定。
    """
    t = _norm(text)
    if not t or is_non_action_message(t):
        return False
    m = _GEN_PHRASE_RE.search(t)
    if m:
        return True
    return any(k in t for k in ("帮我", "请帮我", "给我"))
