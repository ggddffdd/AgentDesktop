# -*- coding: utf-8 -*-
"""小臭玩AI — 统一「非指令判据」（v4.168.0）

为什么要有这个模块
------------------
BUG（对话误调用工具）的根因**不是模型发疯**，而是本地三套路由判断
各修了一部分「评价句豁免」，却**从未共用同一条判据**：

    普通对话输入
      → ui._message_needs_agent()     决定「是否自动进 Agent」
      → agent._detect_action_intent() 决定「是否算需要执行动作」
      → 模型调用层                    决定「是否强制 tool_choice」
      → 三处都对「这个视频生成得真不错」判成"媒体生成请求" → 真去生视频

修法不是继续补词表（开集永远补不完），而是把「是否为明确动作指令」
抽成**唯一判据**，UI / Agent / 模型调用三层都从这里取，杜绝再次漂移。

对外只有两个主入口
------------------
    is_non_action_message(text)   # 层1(UI 自动路由) + 层2(Agent 意图判断)
    blocks_tool_call(text)        # 层3(模型调用层 tool_choice="none")

以及一个诊断入口：

    explain(text) -> dict         # 命中原因明细，供测试/排查用

设计纪律
--------
1. **零依赖**：纯标准库，不 import Qt / tools / agent —— 离线单测可直接跑。
2. **只治误触**：判据命中只会「少调工具」，绝不让真指令变得更容易误触。
   宁可漏报（把真指令当评价）也不误报（把评价当指令去花钱生成）。
3. **加豁免前先想清楚闭集**：凡「排除类」判断一律用一票否决表或位置判据，
   不做前向白名单枚举（本项目已经在这上面栽过五次）。
"""
import re

VERSION = "v4.168.0"

# --------------------------------------------------------------------------
# 一、否定 / 喊停（一票否决）
# --------------------------------------------------------------------------
# v4.159.2 起沿用：用户在取消 / 拒绝 / 喊停生成时，绝不路由生成工具。
# 误报（错杀真指令）只是安全侧漏报，可接受；漏报（没拦住取消）会触发
# 「用户喊停反而被强制生成」，危害大得多 —— 故覆盖面刻意略宽。
_NEG_PHRASES = (
    "别生成", "别做", "别搞", "别弄", "别画", "别拍", "别发", "别去",
    "别再", "先别", "别急", "别管", "别碰", "别了", "不用", "不要",
    "取消", "停止", "别理", "别动", "别提",
    "不做", "不弄", "不搞", "不生成", "不剪", "不拍", "不画",
    "不做了", "先不做了", "再想想", "以后再说", "算了", "先不做",
)

# 裸「别」字：前向复合词闭集豁免 + 后向紧贴一字判据
# （辨别 / 识别 / 类别 / 个别 / 送别 / 别扭 / 特别 / 分别 / 差别 都不是否定词）
_NEG_COMPOUND_BEFORE = set("特分差辨识类个送级性别离区辞样致")
_NEG_TAIL_VERB = ("做", "搞", "弄", "画", "拍", "剪", "发", "去", "来", "写", "合", "拼", "接")
_NEG_TAIL_PARTICLE = "了呀啊吧"

# --------------------------------------------------------------------------
# 二、评价 / 夸赞（含动补结构）
# --------------------------------------------------------------------------
# 动补结构：「生成动词 + 的/得 + (程度副词) + 褒义形容词」
#   「这个视频生成得真不错」「刚才图片做得太惊艳了」「视频制作得挺好」
# 关键收窄：动词必须**紧贴** 的/得 —— 正常祈使句（「做一张好看的图」）动词后
# 没有 的/得 紧贴，不受影响。
_PRAISE_COMPLEMENT_RE = re.compile(
    r"(做|干|写|拍|画|剪|整|弄|搞|设计|生成|制作|编辑)"
    r"(的|得)"
    r"(很|挺|真|超|太|非常|十分|特别|蛮|相当|还|更|极|够|贼|巨|老|最)?"
    r"(好|漂亮|不错|棒|美|清楚|干净|到位|赞|妙|厉害|完美|出色|好看|惊艳|绝|顶|"
    r"牛|强|神|一流|优秀)"
)

# 短语类评价（不是动补结构，但同样是"在评价"而不是"在下指令"）
_PRAISE_KW = (
    "颠覆认知", "真好用", "太强了", "真强", "效果不错", "效果真好", "效果太",
    "好厉害", "绝了", "厉害", "惊艳", "超出预期", "意想不到", "没想到这么",
    "生成得不错", "画得不错", "做得好", "很强", "真不错", "服了",
    "牛啊", "太牛了", "有点东西", "可以啊", "挺不错", "太棒", "真棒",
    "做得很", "生成得很", "效果真",
)

# --------------------------------------------------------------------------
# 三、明确祈使（评价判据的一票反否决）
# --------------------------------------------------------------------------
# 「做得不错，继续」「效果真好，再来一版」—— 先说评价再下指令，属**真指令**。
# 命中祈使词 → 评价/疑问判据一律不成立。
_IMPERATIVE_KW = (
    "帮我", "请生成", "请画", "请做", "请写", "请制作", "请帮",
    "生成一张", "画一张", "做一张", "来一张", "出个视频", "做个视频",
    "做一个", "写一段", "帮我做", "帮我画", "帮我生成", "来一个", "整一个",
    "继续", "接着", "下一步", "往下", "然后", "再来一版", "再生成",
    "重新生成", "重做", "改成", "换成", "修改", "改一下", "重画", "重新做",
)

# --------------------------------------------------------------------------
# 四、引用 / 质疑语境
# --------------------------------------------------------------------------
# 「你刚才说的生成个视频，是BUG」「我什么时候让你生成视频了」
# 显式引用标记（无歧义，可直接一票否决）
_STRONG_REF_KW = (
    "你刚才说的", "你刚才说", "你说的那个", "你说的这", "你说的那",
    "什么时候让你", "什么时候让我", "我什么时候让", "是bug", "是 bug",
    "这也叫bug", "刚才那个bug",
)
# 位置判据：元话语动词出现在「生成短语」之前 → 生成短语是被讨论的对象
_META_VERBS = (
    "分析下", "分析一下", "聊聊", "聊一下", "聊一聊", "谈一下", "谈谈",
    "说说", "说说看", "解释", "解释下", "解释一下", "诊断", "复盘",
    "怎么看", "怎么理解", "为什么", "怎么回事", "咋回事", "什么原因",
    "原因在哪", "评价", "评价下", "评估", "评估下", "隐患", "自检", "自我诊断",
)
_CLAUSE_SEP = ("，", "。", "；", "？", "?", "然后", "顺便", "并且", "而且",
               "再", "之后", "完后", "以及", "并", "、")
_GEN_PHRASE_RE = re.compile(
    r"(生成|做|制作|剪|剪辑|画|拍|合成|搞|弄|整|设计|出|创作)"
    r"[^，。；？！,;?]{0,6}?"
    r"(视频|短片|短视频|片子|动画|图片|照片|插画|海报|封面|头像|数字人|口播|成片|成品|mv)"
)

# --------------------------------------------------------------------------
# 五、咨询 / 学习 / 方法疑问
# --------------------------------------------------------------------------
# 「视频怎么生成的？」「配音怎么学」—— 用户在**问知识**，不是让动手。
_LEARNING_KW = (
    "怎么学", "如何学", "怎么入门", "如何入门", "怎么开始", "是什么", "什么意思",
    "啥意思", "了解一下", "了解下", "介绍下", "介绍一下", "原理", "教程",
    "怎么来的", "会不会", "能不能学", "学习路径", "从哪学", "选哪个", "推荐学习",
    "怎么弄的", "怎么做出来",
)
_HOWTO_KW = (
    "怎么生成的", "怎么做出来的", "怎么弄出来的", "怎么做的", "怎么弄的",
    "怎么实现", "生成原理", "制作原理", "是什么原理",
    "怎么生成", "如何生成", "怎么制作", "如何制作", "怎么剪", "怎么拍",
    "怎么配音", "怎么合成", "怎么弄出来", "如何做到",
)

# 纯陈述 / 感慨特征（与 ui._STATEMENT_HINTS 同源，抽到这里共享）
_STATEMENT_HINTS = (
    "好难", "真难", "太难", "好累", "好烦", "不容易", "没想到", "感觉",
    "我觉得", "怎么这么", "又失败了", "今天", "最近",
)
_QUESTION_TAIL = ("？", "?", "吗", "呢", "么")


# ==========================================================================
# 判据实现
# ==========================================================================

def _norm(text):
    return (text or "").strip()


def is_negation(text):
    """是否「取消 / 拒绝 / 喊停」—— 一票否决，绝不为它调工具。

    v4.159.4 定式：裸「别」字不用前向白名单枚举（辨别/识别/类别/个别/送别/
    别扭 永远补不完），改「前向复合词闭集豁免 + 后向紧贴一字判据」。
    """
    if not text:
        return False
    for k in _NEG_PHRASES:
        if k in text:
            return True
    for m in re.finditer("别", text):
        i = m.start()
        if i > 0 and text[i - 1] in _NEG_COMPOUND_BEFORE:
            continue          # 复合词的一部分，非否定词
        if text[i:i + 2] == "别扭":
            continue
        tail0 = text[i + 1:i + 2]
        if tail0 in _NEG_TAIL_VERB or tail0 in _NEG_TAIL_PARTICLE:
            return True
    return False


def has_imperative(text):
    """是否含明确祈使 / 续接指令 —— 评价与咨询判据的一票反否决。"""
    if not text:
        return False
    t = text.lower()
    return any(k in t for k in _IMPERATIVE_KW)


def is_praise(text):
    """是否「纯评价 / 夸赞」而非动作指令。

    「这个视频生成得真不错」「刚才图片做得太惊艳了」「Agnes 的视频效果真强」
    这些句子里同时出现了媒体对象词（视频/图片）与动作词（生成/制作），
    旧判据的「对象词 × 动作词同现」必然误判 —— 这里先认评价结构。
    """
    if not text:
        return False
    if has_imperative(text):
        return False           # 「做得不错，继续」是真指令
    if _PRAISE_COMPLEMENT_RE.search(text):
        return True
    t = text.lower()
    return any(k in t for k in _PRAISE_KW)


def is_learning_question(text):
    """是否「学习 / 科普 / 了解」类纯咨询问句。"""
    if not text:
        return False
    if has_imperative(text):
        return False
    t = text.lower()
    return any(k in t for k in _LEARNING_KW)


def is_howto_question(text):
    """是否在问「这一步是怎么做到的」—— 要答案，不要产物。"""
    if not text:
        return False
    if has_imperative(text):
        return False
    t = text.lower()
    return any(k in t for k in _HOWTO_KW)


def is_ref_context(text):
    """是否在「引用 / 质疑 / 讨论」某个生成动作，而非下达它。

    两条腿：
      · 显式引用标记（「你刚才说的生成个视频，是BUG」）
      · 位置判据：元话语动词出现在生成短语之前且同分句
        （「分析下生成视频这件事」→ 生成短语是被分析的对象）
    """
    if not text:
        return False
    if any(k in text for k in _STRONG_REF_KW):
        return True
    m = _GEN_PHRASE_RE.search(text)
    if not m:
        return False
    prefix = text[:m.start()]
    if any(sep in prefix for sep in _CLAUSE_SEP):
        return False           # 「生成个视频，顺便分析下」→ 生成是独立指令
    return any(mv in prefix for mv in _META_VERBS)


def is_pure_statement(text):
    """是否「纯陈述 / 感慨」—— 有陈述色彩且无执行意图词。"""
    if not text:
        return False
    t = text.lower()
    if not any(h.lower() in t for h in _STATEMENT_HINTS):
        return False
    if has_imperative(text):
        return False
    return not any(h in t for h in _ACTION_HINT_KW)


# 与 ui._ACTION_HINTS 同源的「执行意图词」最小集（用于纯陈述判定）。
_ACTION_HINT_KW = (
    "搜索", "搜", "查", "写", "生成", "做", "执行", "分析", "整理", "导出",
    "下载", "安装", "运行", "创建", "打开", "发", "截图", "提醒", "翻译", "总结",
    "爬", "抓", "监控", "帮我", "请", "处理", "改", "修", "看下", "看看",
)


